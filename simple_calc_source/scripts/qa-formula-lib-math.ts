import type { Harness } from './qa-formula-library.ts'

// Expected values are Excel results (Microsoft documentation examples where available).
export default function run(h: Harness): void {
  h.section('math')
  const { eq, near, rowsEq, rowsNear } = h

  // Sums of squares.
  eq('SUMSQ(3,4)', 25)
  eq('SUMSQ(A1:A3)', 14)
  eq('SUMSQ(C1:C5)', 9) // range ignores text and logicals
  eq('SUMSQ("3",TRUE)', 10) // direct arguments coerce
  eq('SUMSQ(1/0)', '#DIV/0!')
  eq('SUMSQ(A1:A10)', 385)
  eq('SUMX2MY2({2,3,9,1,8,7,5},{6,5,11,7,5,4,4})', -55)
  eq('SUMX2PY2({2,3,9,1,8,7,5},{6,5,11,7,5,4,4})', 521)
  eq('SUMXMY2({2,3,9,1,8,7,5},{6,5,11,7,5,4,4})', 79)
  eq('SUMX2MY2(D1:D7,E1:E7)', -55)
  eq('SUMX2PY2(D1:D7,E1:E7)', 521)
  eq('SUMXMY2(D1:D7,E1:E7)', 79)
  eq('SUMXMY2({1,2},{1,2,3})', '#N/A')
  eq('SUMXMY2(C1:C3,A1:A3)', 0) // only the numeric pair (3,3) counts
  eq('SUMX2MY2({1,#N/A},{1,2})', '#N/A')

  // Number theory.
  eq('GCD(5,2)', 1)
  eq('GCD(24,36)', 12)
  eq('GCD(7,1)', 1)
  eq('GCD(5,0)', 5)
  eq('GCD(0,0)', 0)
  eq('GCD(24.9,36)', 12)
  eq('GCD(12,18,27)', 3)
  eq('GCD(-1,2)', '#NUM!')
  eq('GCD(A1:A10)', 1)
  eq('LCM(5,2)', 10)
  eq('LCM(24,36)', 72)
  eq('LCM(3,4,6)', 12)
  eq('LCM(0,5)', 0)
  eq('LCM(-1,2)', '#NUM!')
  eq('LCM(A1:A10)', 2520)
  eq('QUOTIENT(5,2)', 2)
  eq('QUOTIENT(4.5,3.1)', 1)
  eq('QUOTIENT(-10,3)', -3)
  eq('QUOTIENT(1,0)', '#DIV/0!')
  eq('QUOTIENT("a",1)', '#VALUE!')

  // Factorials and combinatorics.
  eq('FACT(5)', 120)
  eq('FACT(1.9)', 1)
  eq('FACT(0)', 1)
  eq('FACT(-1)', '#NUM!')
  eq('FACT(20)', 2432902008176640000)
  near('FACT(170)', 7.257415615307994e306, 1e-12)
  eq('FACT(171)', '#NUM!')
  eq('FACTDOUBLE(6)', 48)
  eq('FACTDOUBLE(7)', 105)
  eq('FACTDOUBLE(0)', 1)
  eq('FACTDOUBLE(-1)', 1)
  eq('FACTDOUBLE(-2)', '#NUM!')
  eq('COMBIN(8,2)', 28)
  eq('COMBIN(10,0)', 1)
  eq('COMBIN(8.9,2.9)', 28)
  eq('COMBIN(52,5)', 2598960)
  near('COMBIN(60,30)', 1.1826458156486142e17, 1e-12)
  eq('COMBIN(5,6)', '#NUM!')
  eq('COMBIN(-1,0)', '#NUM!')
  eq('COMBINA(4,3)', 20)
  eq('COMBINA(10,3)', 220)
  eq('COMBINA(0,0)', 1)
  eq('COMBINA(3,0)', 1)
  eq('COMBINA(-1,2)', '#NUM!')
  eq('MULTINOMIAL(2,3,4)', 1260)
  eq('MULTINOMIAL(1,2)', 3)
  eq('MULTINOMIAL(0)', 1)
  eq('MULTINOMIAL(-1,2)', '#NUM!')
  eq('MULTINOMIAL(A1:A3)', 60)

  // Radix and roman numerals.
  eq('BASE(7,2)', '111')
  eq('BASE(100,16)', '64')
  eq('BASE(100,16,4)', '0064')
  eq('BASE(15,2,10)', '0000001111')
  eq('BASE(255,16)', 'FF')
  eq('BASE(35,36)', 'Z')
  eq('BASE(0,2)', '0')
  eq('BASE(-1,2)', '#NUM!')
  eq('BASE(10,1)', '#NUM!')
  eq('BASE(10,37)', '#NUM!')
  eq('BASE(10,2,256)', '#NUM!')
  eq('DECIMAL("FF",16)', 255)
  eq('DECIMAL(111,2)', 7)
  eq('DECIMAL("zap",36)', 45745)
  eq('DECIMAL("ff",16)', 255)
  eq('DECIMAL("2",2)', '#NUM!')
  eq('DECIMAL("FF",37)', '#NUM!')
  eq('ROMAN(499,0)', 'CDXCIX')
  eq('ROMAN(499,1)', 'LDVLIV')
  eq('ROMAN(499,2)', 'XDIX')
  eq('ROMAN(499,3)', 'VDIV')
  eq('ROMAN(499,4)', 'ID')
  eq('ROMAN(499)', 'CDXCIX')
  eq('ROMAN(499,TRUE)', 'CDXCIX')
  eq('ROMAN(499,FALSE)', 'ID')
  eq('ROMAN(1999)', 'MCMXCIX')
  eq('ROMAN(1999,4)', 'MIM')
  eq('ROMAN(3999)', 'MMMCMXCIX')
  eq('ROMAN(2024)', 'MMXXIV')
  eq('ROMAN(49)', 'XLIX')
  eq('ROMAN(0)', '')
  eq('ROMAN(4000)', '#VALUE!')
  eq('ROMAN(-1)', '#VALUE!')
  eq('ROMAN(10,5)', '#VALUE!')
  eq('ARABIC("MCMXII")', 1912)
  eq('ARABIC("mcmxii")', 1912)
  eq('ARABIC("LVII")', 57)
  eq('ARABIC("MMMCMXCIX")', 3999)
  eq('ARABIC("-MMXI")', -2011)
  eq('ARABIC("")', 0)
  eq('ARABIC("ABC")', '#VALUE!')
  eq('ARABIC(5)', '#VALUE!')
  eq('ARABIC(ROMAN(1234))', 1234)
  eq('ARABIC(ROMAN(1999,4))', 1999)

  // Series.
  const series = { K1: 1, K2: -1 / 2, K3: 1 / 24, K4: -1 / 720 }
  near('SERIESSUM(PI()/4,0,2,K1:K4)', 0.707103215, 1e-8, series)
  eq('SERIESSUM(2,1,1,{1,1,1})', 14)
  eq('SERIESSUM(2,1,1,{1,"a"})', '#VALUE!')

  // Reciprocal and hyperbolic trigonometry.
  near('SEC(45)', 1.903594407, 1e-9)
  near('SEC(30)', 6.482921235, 1e-9)
  eq('SEC(0)', 1)
  eq('SEC(2^27)', '#NUM!')
  near('CSC(15)', 1.537780562, 1e-9)
  eq('CSC(0)', '#DIV/0!')
  near('COT(30)', -0.156119952, 1e-8)
  eq('COT(0)', '#DIV/0!')
  near('SINH(1)', 1.175201194, 1e-9)
  near('COSH(4)', 27.30823284, 1e-9)
  near('TANH(-2)', -0.96402758, 1e-8)
  near('TANH(0.5)', 0.462117157, 1e-9)
  eq('SINH(1000)', '#NUM!')
  near('ASINH(-2.5)', -1.647231146, 1e-9)
  near('ASINH(10)', 2.99822295, 1e-9)
  eq('ACOSH(1)', 0)
  near('ACOSH(10)', 2.993222846, 1e-9)
  eq('ACOSH(0.5)', '#NUM!')
  near('ATANH(0.76159416)', 1.00000001, 1e-8)
  near('ATANH(-0.1)', -0.100335348, 1e-9)
  eq('ATANH(1)', '#NUM!')
  near('ACOT(2)', 0.463647609, 1e-9)
  near('ACOT(0)', Math.PI / 2)
  near('ACOT(-1)', (3 * Math.PI) / 4)
  near('ACOTH(6)', 0.168236118, 1e-9)
  eq('ACOTH(1)', '#NUM!')
  eq('ACOTH(0.5)', '#NUM!')
  near('COTH(2)', 1.037314721, 1e-9)
  eq('COTH(0)', '#DIV/0!')
  near('CSCH(1.5)', 0.469642441, 1e-9)
  eq('CSCH(0)', '#DIV/0!')
  near('SECH(45)', 5.725037161e-20, 1e-9)
  near('SECH(0.5)', 0.886818884, 1e-9)
  rowsNear('SINH({0,1})', [[0, 1.1752011936438014]])

  // Precise ceiling/floor.
  eq('CEILING.PRECISE(4.3)', 5)
  eq('CEILING.PRECISE(-4.3)', -4)
  eq('CEILING.PRECISE(4.3,2)', 6)
  eq('CEILING.PRECISE(4.3,-2)', 6)
  eq('CEILING.PRECISE(-4.3,2)', -4)
  eq('CEILING.PRECISE(-4.3,-2)', -4)
  eq('CEILING.PRECISE(4.3,0)', 0)
  eq('CEILING.PRECISE(0.234,0.01)', 0.24)
  eq('ISO.CEILING(4.3)', 5)
  eq('ISO.CEILING(-4.3)', -4)
  eq('ISO.CEILING(4.3,2)', 6)
  eq('ISO.CEILING(-4.3,-2)', -4)
  eq('FLOOR.PRECISE(-3.2,-1)', -4)
  eq('FLOOR.PRECISE(3.2,1)', 3)
  eq('FLOOR.PRECISE(-3.2,1)', -4)
  eq('FLOOR.PRECISE(3.2,-1)', 3)
  eq('FLOOR.PRECISE(3.2)', 3)
  eq('FLOOR.PRECISE(0)', 0)
  eq('FLOOR.PRECISE(7,0)', 0)
  eq('FLOOR.PRECISE("x")', '#VALUE!')

  // Matrices.
  rowsEq('MMULT({1,3;7,2},{2,0;0,2})', [[2, 6], [14, 4]])
  rowsEq('MMULT(G1:H3,{1;1})', [[3], [7], [11]])
  rowsEq('MMULT({1,2,3},{4;5;6})', [[32]])
  eq('MMULT({1,2},{1,2})', '#VALUE!')
  eq('MMULT({1,"a"},{1;2})', '#VALUE!')
  eq('MMULT({1,2},{1;#N/A})', '#N/A')
  rowsEq('MINVERSE({4,-1;2,0})', [[0, 0.5], [-1, 2]])
  rowsNear('MINVERSE({1,2,1;3,4,-1;0,2,0})', [[0.25, 0.25, -0.75], [0, 0, 0.5], [0.75, -0.25, -0.25]], 1e-12)
  rowsNear('MMULT(MINVERSE({2,1;7,4}),{2,1;7,4})', [[1, 0], [0, 1]], 1e-12)
  eq('MINVERSE({1,2;2,4})', '#NUM!')
  eq('MINVERSE({1,2,3;4,5,6;7,8,9})', '#NUM!')
  eq('MINVERSE({1,2,3})', '#VALUE!')
  eq('MINVERSE({0})', '#NUM!')
  eq('MDETERM({1,3,8,5;1,3,6,1;1,1,1,0;7,3,10,2})', 88)
  eq('MDETERM({3,6;1,1})', -3)
  eq('MDETERM({3,6,1;1,1,0;3,10,2})', 1)
  eq('MDETERM({1,3,8,5;1,3,6,1})', '#VALUE!')
  eq('MDETERM({5})', 5)
  eq('MDETERM({1,2;2,4})', 0)
  eq('MDETERM(G1:H2)', -2)
  rowsEq('MUNIT(3)', [[1, 0, 0], [0, 1, 0], [0, 0, 1]])
  eq('MUNIT(1)', 1)
  eq('MUNIT(0)', '#VALUE!')

  // Google Sheets operator functions.
  eq('ADD(1,2)', 3)
  eq('MINUS(5,3)', 2)
  eq('MULTIPLY(2,3)', 6)
  eq('DIVIDE(6,3)', 2)
  eq('DIVIDE(1,0)', '#DIV/0!')
  eq('POW(2,10)', 1024)
  eq('EQ("a","A")', true)
  eq('NE(1,2)', true)
  eq('GT(2,1)', true)
  eq('GTE(1,1)', true)
  eq('LT(1,2)', true)
  eq('LTE(2,1)', false)
  eq('UMINUS(5)', -5)
  eq('UPLUS("abc")', 'abc')
  eq('UNARY_PERCENT(50)', 0.5)
  rowsEq('ADD(A1:A3,1)', [[2], [3], [4]])

  // Lifting over arrays.
  rowsEq('FACT(A1:A4)', [[1], [2], [6], [24]])
  rowsEq('COMBIN(5,{0,1,2})', [[1, 5, 10]])
  rowsEq('QUOTIENT(A1:A3,2)', [[0], [1], [1]])
  rowsEq('ROMAN({1,5,10})', [['I', 'V', 'X']])
}
