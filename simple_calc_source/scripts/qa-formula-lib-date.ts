import type { Harness } from './qa-formula-library.ts'

// Expected values come from Microsoft's function documentation examples (full-precision
// values were cross-checked against the rounded figures Excel displays) and from the
// reverse-engineered YEARFRAC rules (D. A. Wheeler's analysis of Excel's algorithm).
export default function run(h: Harness): void {
  h.section('date: DAYS360')
  h.eq('DAYS360(DATE(2011,1,1),DATE(2011,12,31))', 360)
  h.eq('DAYS360(DATE(2011,1,30),DATE(2011,2,1))', 1)
  h.eq('DAYS360(DATE(2011,1,30),DATE(2011,12,31))', 330)
  h.eq('DAYS360(DATE(2011,1,31),DATE(2011,2,28))', 28)
  h.eq('DAYS360(DATE(2011,2,28),DATE(2011,3,31))', 30)
  h.eq('DAYS360(DATE(2011,1,1),DATE(2011,1,31))', 30)
  h.eq('DAYS360(DATE(2011,1,1),DATE(2011,1,31),TRUE)', 29)
  h.eq('DAYS360(DATE(2011,1,31),DATE(2011,3,31),TRUE)', 60)
  h.eq('DAYS360(DATE(2011,1,31),DATE(2011,3,31),FALSE)', 60)
  h.eq('DAYS360(DATE(2012,2,29),DATE(2012,3,31))', 30)
  h.eq('DAYS360(DATE(2012,2,29),DATE(2012,3,31),TRUE)', 31)
  h.eq('DAYS360(DATE(2020,1,15),DATE(2021,1,15))', 360)
  h.eq('DAYS360(DATE(2021,1,15),DATE(2020,1,15))', -360)
  h.eq('DAYS360("2011-01-01","2011-12-31")', 360)
  h.eq('DAYS360(A1,A1)', 0)
  h.eq('DAYS360(-1,5)', '#NUM!')
  h.eq('DAYS360("abc",1)', '#VALUE!')
  h.eq('DAYS360(1)', '#VALUE!')
  h.rowsEq('DAYS360(DATE(2011,1,1),{"2011-02-01","2011-03-01"})', [[30, 60]])

  h.section('date: YEARFRAC')
  h.near('YEARFRAC(DATE(2012,1,1),DATE(2012,7,30))', 0.5805555555555556)
  h.near('YEARFRAC(DATE(2012,1,1),DATE(2012,7,30),0)', 0.5805555555555556)
  h.near('YEARFRAC(DATE(2012,1,1),DATE(2012,7,30),1)', 211 / 366)
  h.near('YEARFRAC(DATE(2012,1,1),DATE(2012,7,30),2)', 211 / 360)
  h.near('YEARFRAC(DATE(2012,1,1),DATE(2012,7,30),3)', 211 / 365)
  h.near('YEARFRAC(DATE(2012,1,1),DATE(2012,7,30),4)', 209 / 360)
  h.near('YEARFRAC(DATE(2012,7,30),DATE(2012,1,1),1)', 211 / 366)
  h.eq('YEARFRAC(DATE(2012,1,1),DATE(2012,1,1))', 0)
  h.near('YEARFRAC(DATE(2000,1,1),DATE(2004,6,30),1)', 1642 / (1827 / 5))
  h.eq('YEARFRAC(DATE(2011,2,28),DATE(2012,2,29),0)', 1)
  h.near('YEARFRAC(DATE(2011,1,31),DATE(2011,3,31),0)', 60 / 360)
  h.near('YEARFRAC(DATE(2011,1,30),DATE(2011,3,31),0)', 60 / 360)
  h.near('YEARFRAC(DATE(2011,1,15),DATE(2011,3,31),0)', 76 / 360)
  h.near('YEARFRAC(DATE(2011,2,28),DATE(2011,3,15),0)', 15 / 360)
  h.near('YEARFRAC(DATE(2012,2,29),DATE(2013,2,28),1)', 365 / 366)
  h.eq('YEARFRAC(DATE(2011,12,31),DATE(2012,12,31),1)', 1)
  h.near('YEARFRAC(DATE(2011,6,1),DATE(2012,3,1),1)', 274 / 366)
  h.near('YEARFRAC(DATE(2010,6,1),DATE(2011,3,1),1)', 273 / 365)
  h.near('YEARFRAC(DATE(2011,1,1),DATE(2011,12,31),1)', 364 / 365)
  h.near('YEARFRAC(DATE(2012,1,1),DATE(2012,12,31),1)', 365 / 366)
  h.near('YEARFRAC(DATE(2011,7,1),DATE(2013,7,1),3)', 731 / 365)
  h.near('YEARFRAC("2012-01-01","2012-07-30",2)', 211 / 360)
  h.eq('YEARFRAC(DATE(2012,1,1),DATE(2012,7,30),5)', '#NUM!')
  h.eq('YEARFRAC(DATE(2012,1,1),DATE(2012,7,30),-1)', '#NUM!')
  h.eq('YEARFRAC(-5,10)', '#NUM!')
  h.eq('YEARFRAC("x",10)', '#VALUE!')
  h.rowsNear('YEARFRAC(DATE(2012,1,1),DATE(2012,7,30),{2,3})', [[211 / 360, 211 / 365]])

  h.section('date: ISOWEEKNUM')
  h.eq('ISOWEEKNUM(DATE(2012,3,9))', 10)
  h.eq('ISOWEEKNUM(DATE(2021,1,1))', 53)
  h.eq('ISOWEEKNUM(DATE(2020,12,31))', 53)
  h.eq('ISOWEEKNUM(DATE(2021,1,4))', 1)
  h.eq('ISOWEEKNUM(DATE(2019,12,30))', 1)
  h.eq('ISOWEEKNUM(DATE(2008,12,29))', 1)
  h.eq('ISOWEEKNUM(DATE(2010,1,3))', 53)
  h.eq('ISOWEEKNUM(DATE(2010,1,4))', 1)
  h.eq('ISOWEEKNUM(DATE(2024,12,29))', 52)
  h.eq('ISOWEEKNUM(DATE(2024,12,30))', 1)
  h.eq('ISOWEEKNUM("2012-03-09")', 10)
  h.eq('ISOWEEKNUM(-1)', '#NUM!')
  h.eq('ISOWEEKNUM("soon")', '#VALUE!')
  h.rowsEq('ISOWEEKNUM({"2021-01-01";"2021-01-04"})', [[53], [1]])
  for (let year = 2000; year <= 2030; year += 1) {
    for (const [month, day] of [[1, 1], [3, 15], [6, 30], [12, 28], [12, 31]]) {
      const iso = h.value(`ISOWEEKNUM(DATE(${year},${month},${day}))`)
      const weeknum21 = h.value(`WEEKNUM(DATE(${year},${month},${day}),21)`)
      h.check(`ISOWEEKNUM = WEEKNUM(,21) for ${year}-${month}-${day}`, iso === weeknum21, `${iso} vs ${weeknum21}`)
    }
  }

  h.section('date: NETWORKDAYS.INTL')
  h.eq('NETWORKDAYS.INTL(DATE(2006,1,1),DATE(2006,1,31))', 22)
  h.eq('NETWORKDAYS.INTL(DATE(2006,2,28),DATE(2006,1,31))', -21)
  h.eq('NETWORKDAYS.INTL(DATE(2006,1,1),DATE(2006,2,1),7,{"2006/1/2","2006/1/16"})', 22)
  h.eq('NETWORKDAYS.INTL(DATE(2006,1,1),DATE(2006,2,1),"0010001",{"2006/1/2","2006/1/16"})', 20)
  h.eq('NETWORKDAYS.INTL(DATE(2012,10,1),DATE(2013,3,1))', 110)
  h.eq('NETWORKDAYS.INTL(DATE(2012,10,1),DATE(2013,3,1),1,DATE(2012,11,22))', 109)
  h.eq('NETWORKDAYS.INTL(DATE(2012,10,1),DATE(2013,3,1),1,{41235,41247,41295})', 107)
  h.eq('NETWORKDAYS.INTL(DATE(2012,10,1),DATE(2013,3,1),"0000011",{41235,41247,41295})', 107)
  h.eq('NETWORKDAYS.INTL(DATE(2012,10,1),DATE(2013,3,1),,{41235,41247,41295})', 107)
  // Duplicate holidays and holidays on weekends are not double-counted.
  h.eq('NETWORKDAYS.INTL(DATE(2012,10,1),DATE(2013,3,1),1,{41235,41235,41237})', 109)
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),11)', 6)
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),17)', 6)
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),2)', 5)
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),"1111100")', 2)
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),"0000000")', 7)
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,6),DATE(2024,1,6))', 0)
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,8),DATE(2024,1,8))', 1)
  h.eq('NETWORKDAYS.INTL(DATE(2000,1,1),DATE(2050,12,31),11)', 15967)
  h.eq('NETWORKDAYS.INTL(DATE(2000,1,1),DATE(2050,12,31),1)', h.value('NETWORKDAYS(DATE(2000,1,1),DATE(2050,12,31))') as number)
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),8)', '#NUM!')
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),0)', '#NUM!')
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),"000001")', '#VALUE!')
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),"0000012")', '#VALUE!')
  h.eq('NETWORKDAYS.INTL(DATE(2024,1,1),DATE(2024,1,7),1,"soon")', '#VALUE!')
  h.eq('NETWORKDAYS.INTL(-1,DATE(2024,1,7))', '#NUM!')
  h.eq('NETWORKDAYS.INTL("x",DATE(2024,1,7))', '#VALUE!')
  h.rowsEq('NETWORKDAYS.INTL(DATE(2024,1,1),{"2024-01-05","2024-01-12"})', [[5, 10]])
  for (const [start, end] of [[40000, 40100], [40100, 40000], [44000, 44003], [45000, 46000], [36526, 36530]]) {
    const intl = h.value(`NETWORKDAYS.INTL(${start},${end},1,{40050,45100,45101})`)
    const plain = h.value(`NETWORKDAYS(${start},${end},{40050,45100,45101})`)
    h.check(`NETWORKDAYS.INTL code 1 = NETWORKDAYS ${start}..${end}`, intl === plain, `${intl} vs ${plain}`)
  }

  h.section('date: WORKDAY.INTL')
  h.eq('WORKDAY.INTL(DATE(2012,1,1),30,0)', '#NUM!')
  h.eq('WORKDAY.INTL(DATE(2012,1,1),90,11)', 41013)
  h.eq('WORKDAY.INTL(DATE(2012,1,1),30,17)', 40944)
  h.eq('WORKDAY.INTL(DATE(2008,10,1),151)', 39933)
  h.eq('WORKDAY.INTL(DATE(2008,10,1),151,1,{39777,39800,39826})', 39938)
  h.eq('WORKDAY.INTL(DATE(2008,10,1),151,"0000011",{39777,39800,39826})', 39938)
  h.eq('WORKDAY.INTL(DATE(2024,1,6),0)', 45297)
  h.eq('WORKDAY.INTL(DATE(2024,1,5),1)', 45299)
  h.eq('WORKDAY.INTL(DATE(2024,1,8),-1)', 45296)
  h.eq('WORKDAY.INTL(DATE(2024,1,8),-1,1,DATE(2024,1,5))', 45295)
  h.eq('WORKDAY.INTL(DATE(2024,1,5),1,7)', 45298)
  h.eq('WORKDAY.INTL(DATE(2024,1,5),1,"0000000")', 45297)
  h.eq('WORKDAY.INTL(DATE(2024,1,5),1.9)', 45299)
  h.eq('WORKDAY.INTL(DATE(2024,1,5),1,"1111111")', '#VALUE!')
  h.eq('WORKDAY.INTL(DATE(2024,1,5),1,"11111")', '#VALUE!')
  h.eq('WORKDAY.INTL(DATE(2024,1,5),1,9)', '#NUM!')
  h.eq('WORKDAY.INTL(DATE(2024,1,5),"x")', '#VALUE!')
  h.eq('WORKDAY.INTL(DATE(9999,12,30),10)', '#NUM!')
  h.rowsEq('WORKDAY.INTL(DATE(2024,1,5),{1;2;5})', [[45299], [45300], [45303]])
  for (const days of [1, 5, 6, 7, 10, 25, 151, 260, 1000, 5000, -1, -6, -30, -400]) {
    const intl = h.value(`WORKDAY.INTL(DATE(2008,10,1),${days},1,{39777,39800,39826,39448,40000,40001})`)
    const plain = h.value(`WORKDAY(DATE(2008,10,1),${days},{39777,39800,39826,39448,40000,40001})`)
    h.check(`WORKDAY.INTL code 1 = WORKDAY for ${days} days`, intl === plain, `${intl} vs ${plain}`)
  }
  for (const code of [2, 3, 7, 11, 14, 17]) {
    for (const days of [3, 17, 250, -9]) {
      const end = h.value(`WORKDAY.INTL(DATE(2020,3,4),${days},${code},{43900,43950})`) as number
      const counted = h.value(`NETWORKDAYS.INTL(DATE(2020,3,4)+SIGN(${days}),${end},${code},{43900,43950})`) as number
      h.check(`WORKDAY.INTL/NETWORKDAYS.INTL agree code ${code} days ${days}`, counted === days, `${counted} vs ${days}`)
    }
  }
  h.eq('WORKDAY.INTL(DATE(2000,1,3),100000,1)', h.value('WORKDAY(DATE(2000,1,3),100000)') as number)

  h.section('date: EPOCHTODATE / TO_DATE')
  h.eq('EPOCHTODATE(0)', 25569)
  h.eq('EPOCHTODATE(86400)', 25570)
  h.eq('EPOCHTODATE(86400,1)', 25570)
  h.near('EPOCHTODATE(1655908429662,2)', 25569 + 1655908429.662 / 86400)
  h.near('EPOCHTODATE(1655908429662000,3)', 25569 + 1655908429.662 / 86400)
  h.near('EPOCHTODATE(43200)', 25569.5)
  h.eq('EPOCHTODATE(-1)', '#NUM!')
  h.eq('EPOCHTODATE(1,4)', '#NUM!')
  h.eq('EPOCHTODATE("x")', '#VALUE!')
  h.eq('TO_DATE(44927)', 44927)
  h.eq('TO_DATE("abc")', 'abc')
  h.eq('TO_DATE(TRUE)', true)

  h.section('date: existing functions vs Excel docs')
  h.eq('WEEKNUM(DATE(2012,3,9))', 10)
  h.eq('WEEKNUM(DATE(2012,3,9),2)', 11)
  h.eq('WEEKNUM(DATE(2021,1,1),21)', 53)
  h.eq('DATEDIF(DATE(2001,1,1),DATE(2003,1,1),"Y")', 2)
  h.eq('DATEDIF(DATE(2001,6,1),DATE(2002,8,15),"D")', 440)
  h.eq('DATEDIF(DATE(2001,6,1),DATE(2002,8,15),"YD")', 75)
  h.eq('DATEDIF(DATE(2001,6,1),DATE(2002,8,15),"MD")', 14)
  h.eq('NETWORKDAYS(DATE(2012,10,1),DATE(2013,3,1))', 110)
  h.eq('NETWORKDAYS(DATE(2012,10,1),DATE(2013,3,1),DATE(2012,11,22))', 109)
  h.eq('NETWORKDAYS(DATE(2012,10,1),DATE(2013,3,1),{41235,41247,41295})', 107)
  h.eq('WORKDAY(DATE(2008,10,1),151)', 39933)
  h.eq('WORKDAY(DATE(2008,10,1),151,{39777,39800,39826})', 39938)
  h.eq('EDATE(DATE(2011,1,15),-1)', 40527)
  h.eq('EOMONTH(DATE(2011,1,1),-3)', 40482)
  h.eq('WEEKDAY(DATE(2008,2,14),3)', 3)
  h.eq('DAYS(DATE(2021,3,15),DATE(2021,2,1))', 42)
}
