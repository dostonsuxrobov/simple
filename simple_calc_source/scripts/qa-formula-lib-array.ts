  h.section('array: Sheets helpers')
  h.eq('COUNTUNIQUE(B1:B8)', 5)
  h.eq('COUNTUNIQUE(F1:F4,"APPLE")', 5)
  h.eq('COUNTUNIQUE(1,"1",TRUE)', 3)
  h.eq('COUNTUNIQUE(C1:C5)', 4)
  h.eq('COUNTUNIQUE(A1:A10,A1:A10)', 10)
  h.rowsEq('FLATTEN(G1:H3)', [[1], [2], [3], [4], [5], [6]])
  h.rowsEq('FLATTEN({1,2},{3})', [[1], [2], [3]])
