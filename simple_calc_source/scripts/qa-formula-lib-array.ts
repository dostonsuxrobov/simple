  h.eq('ADDRESS(2,3,1,FALSE)', 'R2C3')
  h.eq('ADDRESS(2,3,1,FALSE,"[Book1]Sheet1")', '[Book1]Sheet1!R2C3')
  h.eq('ADDRESS(2,3,1,FALSE,"EXCEL SHEET")', "'EXCEL SHEET'!R2C3")
  h.eq('ADDRESS(1,1,1,TRUE,"Sheet1")', 'Sheet1!$A$1')
  h.eq('ADDRESS(1,1,1,TRUE,"A1")', "'A1'!$A$1")
