  h.eq('CELL("address",B3)', '$B$3')
  h.eq('CELL("address",Data!B2)', 'Data!$B$2')
  h.eq('CELL("row",B3)', 3)
  h.eq('CELL("col",C7)', 3)
  h.eq('CELL("col",C7:E9)', 3)
  h.eq('CELL("contents",A5)', 5)
  h.eq('CELL("contents",F1)', 'apple')
