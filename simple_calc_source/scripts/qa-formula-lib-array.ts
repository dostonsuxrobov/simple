  h.eq('ADDRESS(1048576,1,4)', 'A1048576')
  h.eq('ADDRESS(0,1)', '#VALUE!')
  h.eq('ADDRESS(1,16385)', '#VALUE!')
  h.eq('ADDRESS(1,1,5)', '#VALUE!')
  h.rowsEq('ADDRESS({1;2},1)', [['$A$1'], ['$A$2']])
