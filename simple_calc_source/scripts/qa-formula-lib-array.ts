  h.eq('ARRAYFORMULA(SUM(A1:A3*2))', 12)
  h.rowsEq('ARRAY_CONSTRAIN(G1:H3,2,1)', [[1], [3]])
  h.rowsEq('ARRAY_CONSTRAIN(G1:H3,9,9)', [[1, 2], [3, 4], [5, 6]])
  h.eq('ARRAY_CONSTRAIN(G1:H3,0,1)', '#NUM!')
  h.rowsEq('SORTN(B1:B8,3)', [[2], [4], [4]])
  h.rowsEq('SORTN(B1:B8,2,1)', [[2], [4], [4], [4]])
  h.rowsEq('SORTN(B1:B8,3,2)', [[2], [4], [5]])
