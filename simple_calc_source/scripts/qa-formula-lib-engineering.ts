import type { Harness } from './qa-formula-library.ts'

// Expected values are Excel results (Microsoft documentation examples where available);
// Bessel checks also use exact identities (Wronskians, recurrences).
export default function run(h: Harness): void {
  h.section('engineering')
  const { eq, near, rowsEq } = h

  /** Compare complex text numerically: IMREAL/IMAGINARY within tolerance. */
  const complexNear = (formula: string, re: number, im: number, tolerance = 1e-12) => {
    near(`IMREAL(${formula})`, re, tolerance)
    near(`IMAGINARY(${formula})`, im, tolerance)
  }

  // Radix conversions.
  eq('BIN2DEC(1100100)', 100)
  eq('BIN2DEC("1111111111")', -1)
  eq('BIN2DEC("1000000000")', -512)
  eq('BIN2DEC("0111111111")', 511)
  eq('BIN2DEC("11111111111")', '#NUM!')
  eq('BIN2DEC("102")', '#NUM!')
  eq('BIN2DEC(TRUE)', '#VALUE!')
  eq('BIN2HEX(11111011,4)', '00FB')
  eq('BIN2HEX(1110)', 'E')
  eq('BIN2HEX("1111111111")', 'FFFFFFFFFF')
  eq('BIN2HEX(11111011,1)', '#NUM!')
  eq('BIN2HEX(1,11)', '#NUM!')
  eq('BIN2HEX(1,"a")', '#VALUE!')
  eq('BIN2OCT(1001,3)', '011')
  eq('BIN2OCT(1100100)', '144')
  eq('BIN2OCT("1111111111")', '7777777777')
  eq('DEC2BIN(9,4)', '1001')
  eq('DEC2BIN(9)', '1001')
  eq('DEC2BIN(9.9)', '1001')
  eq('DEC2BIN(-100)', '1110011100')
  eq('DEC2BIN(-100,2)', '1110011100') // places ignored for negatives
  eq('DEC2BIN(511)', '111111111')
  eq('DEC2BIN(-512)', '1000000000')
  eq('DEC2BIN(512)', '#NUM!')
  eq('DEC2BIN(-513)', '#NUM!')
  eq('DEC2BIN(9,3)', '#NUM!')
  eq('DEC2BIN(9,0)', '#NUM!')
  eq('DEC2BIN("abc")', '#VALUE!')
  eq('DEC2BIN(0)', '0')
  eq('DEC2HEX(100,4)', '0064')
  eq('DEC2HEX(-54)', 'FFFFFFFFCA')
  eq('DEC2HEX(28)', '1C')
  eq('DEC2HEX(64,1)', '#NUM!')
  eq('DEC2HEX(549755813887)', '7FFFFFFFFF')
  eq('DEC2HEX(549755813888)', '#NUM!')
  eq('DEC2HEX(-549755813888)', '8000000000')
  eq('DEC2OCT(58,3)', '072')
  eq('DEC2OCT(-100)', '7777777634')
  eq('DEC2OCT(536870911)', '3777777777')
  eq('DEC2OCT(536870912)', '#NUM!')
  eq('HEX2BIN("F",8)', '00001111')
  eq('HEX2BIN("B7")', '10110111')
  eq('HEX2BIN("FFFFFFFFFF")', '1111111111')
  eq('HEX2BIN("FFFFFFFE00")', '1000000000')
  eq('HEX2BIN("200")', '#NUM!')
  eq('HEX2DEC("A5")', 165)
  eq('HEX2DEC("a5")', 165)
  eq('HEX2DEC("FFFFFFFF5B")', -165)
  eq('HEX2DEC("3DA408B9")', 1034160313)
  eq('HEX2DEC("8000000000")', -549755813888)
  eq('HEX2DEC("G")', '#NUM!')
  eq('HEX2DEC("12345678901")', '#NUM!')
  eq('HEX2OCT("F",3)', '017')
  eq('HEX2OCT("3B4E")', '35516')
  eq('HEX2OCT("FFFFFFFF00")', '7777777400')
  eq('HEX2OCT("20000000")', '#NUM!')
  eq('OCT2BIN(3,3)', '011')
  eq('OCT2BIN(7777777000)', '1000000000')
  eq('OCT2BIN("1000")', '#NUM!')
  eq('OCT2DEC(54)', 44)
  eq('OCT2DEC(7777777533)', -165)
  eq('OCT2DEC("8")', '#NUM!')
  eq('OCT2HEX(100,4)', '0040')
  eq('OCT2HEX(7777777533)', 'FFFFFFFF5B')
  rowsEq('DEC2BIN({1,2,3})', [['1', '10', '11']])
  eq('HEX2DEC(DEC2HEX(123456789))', 123456789)
  eq('OCT2DEC(DEC2OCT(-12345))', -12345)

  // Bitwise operations.
  eq('BITAND(1,5)', 1)
  eq('BITAND(13,25)', 9)
  eq('BITOR(23,10)', 31)
  eq('BITXOR(5,3)', 6)
  eq('BITLSHIFT(4,2)', 16)
  eq('BITRSHIFT(13,2)', 3)
  eq('BITLSHIFT(16,-2)', 4)
  eq('BITRSHIFT(4,-2)', 16)
  eq('BITAND(2^48-1,2^47)', 140737488355328)
  eq('BITOR(2^47,1)', 140737488355329)
  eq('BITXOR(2^47+3,2^47+1)', 2)
  eq('BITLSHIFT(1,47)', 140737488355328)
  eq('BITLSHIFT(1,48)', '#NUM!')
  eq('BITAND(-1,5)', '#NUM!')
  eq('BITAND(1.5,1)', '#NUM!')
  eq('BITAND(2^48,1)', '#NUM!')
  eq('BITOR("a",1)', '#VALUE!')

  // DELTA / GESTEP.
  eq('DELTA(5,4)', 0)
  eq('DELTA(5,5)', 1)
  eq('DELTA(0.5,0)', 0)
  eq('DELTA(0)', 1)
  eq('DELTA("a",1)', '#VALUE!')
  eq('GESTEP(5,4)', 1)
  eq('GESTEP(5,5)', 1)
  eq('GESTEP(-4,-5)', 1)
  eq('GESTEP(-1)', 0)
  eq('SUM(GESTEP(A1:A10,5))', 6)

  // CONVERT.
  eq('CONVERT(1,"lbm","kg")', 0.45359237)
  eq('CONVERT(68,"F","C")', 20)
  eq('CONVERT(6,"C","F")', 42.8)
  eq('CONVERT(2.5,"ft","sec")', '#N/A')
  eq('CONVERT(CONVERT(100,"ft","m"),"ft","m")', 9.290304)
  eq('CONVERT(100,"ft2","m2")', 9.290304)
  eq('CONVERT(1,"Gibyte","Mibyte")', 1024)
  eq('CONVERT(1,"gal","l")', 3.785411784)
  eq('CONVERT(1,"mi","km")', 1.609344)
  eq('CONVERT(1,"in","cm")', 2.54)
  eq('CONVERT(100,"K","C")', -173.15)
  eq('CONVERT(0,"C","K")', 273.15)
  eq('CONVERT(212,"F","K")', 373.15)
  eq('CONVERT(100,"C","Reau")', 80)
  eq('CONVERT(491.67,"Rank","F")', 32)
  eq('CONVERT(1,"hr","mn")', 60)
  eq('CONVERT(1,"yr","day")', 365.25)
  eq('CONVERT(1,"day","sec")', 86400)
  eq('CONVERT(1,"sec","ms")', 1000)
  eq('CONVERT(1,"atm","Pa")', 101325)
  eq('CONVERT(1,"atm","mmHg")', 760)
  near('CONVERT(1,"Pa","psi")', 0.000145037737730209, 1e-12)
  near('CONVERT(1,"kg","lbm")', 2.20462262184878, 1e-13)
  eq('CONVERT(1,"byte","bit")', 8)
  eq('CONVERT(1,"kibyte","byte")', 1024)
  eq('CONVERT(1,"kbyte","byte")', 1000)
  eq('CONVERT(1,"Gibit","bit")', 1073741824)
  near('CONVERT(1,"m","ft")', 3.28083989501312, 1e-13)
  eq('CONVERT(1,"Nmi","m")', 1852)
  eq('CONVERT(1,"ha","m2")', 10000)
  eq('CONVERT(1,"km2","m2")', 1000000)
  eq('CONVERT(1,"cm3","m3")', 0.000001)
  eq('CONVERT(1,"m3","l")', 1000)
  eq('CONVERT(1,"l","ml")', 1000)
  eq('CONVERT(1,"cup","tbs")', 16)
  eq('CONVERT(1,"tbs","tsp")', 3)
  eq('CONVERT(1,"uk_gal","l")', 4.54609)
  eq('CONVERT(1,"barrel","gal")', 42)
  near('CONVERT(1,"in3","l")', 0.016387064, 1e-12)
  eq('CONVERT(1,"HP","W")', 745.69987158227)
  eq('CONVERT(1,"BTU","J")', 1055.05585262)
  eq('CONVERT(1,"cal","J")', 4.1868)
  eq('CONVERT(1,"Wh","J")', 3600)
  eq('CONVERT(1,"kWh","J")', 3600000)
  near('CONVERT(1,"kn","m/s")', 0.514444444444444, 1e-13)
  eq('CONVERT(60,"mph","m/s")', 26.8224)
  eq('CONVERT(1,"lbf","N")', 4.4482216152605)
  eq('CONVERT(1,"T","ga")', 10000)
  near('CONVERT(1,"ft","yd")', 0.333333333333333, 1e-13)
  eq('CONVERT(1,"stone","lbm")', 14)
  eq('CONVERT(1,"ton","lbm")', 2000)
  eq('CONVERT(1,"uk_ton","lbm")', 2240)
  eq('CONVERT(1,"ozm","g")', 28.349523125)
  eq('CONVERT(1,"Mm","m")', 1000000)
  eq('CONVERT(1,"dam","m")', 10)
  eq('CONVERT(1,"mm","m")', 0.001)
  eq('CONVERT(1,"ang","m")', 1e-10)
  eq('CONVERT(1,"ly","m")', 9460730472580800)
  near('CONVERT(1,"pc","ly")', 3.26156377716743, 1e-9)
  near('CONVERT(1,"survey_mi","m")', 1609.34721869444, 1e-13)
  eq('CONVERT(1,"x","m")', '#N/A')
  eq('CONVERT(1,"M","m")', '#N/A')
  eq('CONVERT(1,"kft","m")', '#N/A') // imperial units take no prefixes
  eq('CONVERT(1,"lbm","m")', '#N/A')
  eq('CONVERT("a","m","ft")', '#VALUE!')
  rowsEq('CONVERT({0,100},"C","F")', [[32, 212]])

  // Complex numbers.
  eq('COMPLEX(3,4)', '3+4i')
  eq('COMPLEX(3,4,"j")', '3+4j')
  eq('COMPLEX(0,1)', 'i')
  eq('COMPLEX(0,-1)', '-i')
  eq('COMPLEX(1,0)', '1')
  eq('COMPLEX(0,0)', '0')
  eq('COMPLEX(1.5,-2.25)', '1.5-2.25i')
  eq('COMPLEX(3,4,"k")', '#VALUE!')
  eq('COMPLEX(3,4,"I")', '#VALUE!')
  eq('COMPLEX("a",4)', '#VALUE!')
  eq('IMABS("5+12i")', 13)
  eq('IMABS(-3)', 3)
  eq('IMAGINARY("3+4i")', 4)
  eq('IMAGINARY("0-j")', -1)
  eq('IMAGINARY(4)', 0)
  eq('IMAGINARY("-i")', -1)
  eq('IMAGINARY("i")', 1)
  eq('IMAGINARY("1e2+3e-1i")', 0.3)
  eq('IMREAL("1e2+3e-1i")', 100)
  eq('IMREAL("6-9i")', 6)
  eq('IMREAL("i")', 0)
  eq('IMREAL("-2.5")', -2.5)
  near('IMARGUMENT("3+4i")', 0.92729521800161, 1e-12)
  eq('IMARGUMENT("0")', '#DIV/0!')
  eq('IMCONJUGATE("3+4i")', '3-4i')
  eq('IMCONJUGATE("-i")', 'i')
  eq('IMCOS("1+i")', '0.833730025131149-0.988897705762865i')
  eq('IMEXP("1+i")', '1.46869393991589+2.28735528717884i')
  eq('IMLN("3+4i")', '1.6094379124341+0.927295218001612i')
  eq('IMLOG10("3+4i")', '0.698970004336019+0.402719196273373i')
  eq('IMLOG2("3+4i")', '2.32192809488736+1.33780421245098i')
  eq('IMSIN("3+4i")', '3.85373803791938-27.0168132580039i')
  eq('IMSQRT("1+i")', '1.09868411346781+0.455089860562227i')
  eq('IMPOWER("2+3i",3)', '-46+9.00000000000001i')
  complexNear('IMPOWER("2+3i",3)', -46, 9, 1e-13)
  complexNear('IMPOWER("4",0.5)', 2, 0)
  eq('IMPOWER("0",-1)', '#NUM!')
  eq('IMPRODUCT("3+4i","5-3i")', '27+11i')
  eq('IMPRODUCT("1+2i",30)', '30+60i')
  eq('IMSUB("13+4i","5+3i")', '8+i')
  eq('IMSUM("3+4i","5-3i")', '8+i')
  eq('IMSUM("3+4j","1")', '4+4j')
  eq('IMSUM("3+4i","1+j")', '#VALUE!')
  eq('IMSUM({"1+i","2-i"},"i")', '3+i')
  eq('IMDIV("-238+240i","10+24i")', '5+12i')
  eq('IMDIV("1","0")', '#NUM!')
  eq('IMLN("0")', '#NUM!')
  eq('IMABS("abc")', '#NUM!')
  eq('IMABS("3 + 4i")', '#NUM!')
  eq('IMABS(TRUE)', '#VALUE!')
  complexNear('IMCOSH("4+3i")', -27.0349456030742, 3.85115333481178, 1e-12)
  complexNear('IMSINH("4+3i")', -27.0168132580039, 3.85373803791938, 1e-12)
  complexNear('IMTAN("4+3i")', 0.00490825806749606, 1.00070953606723, 1e-10)
  complexNear('IMCOT("4+3i")', 0.0049011823943045, -0.999266927805902, 1e-10)
  complexNear('IMSEC("4+3i")', -0.0652940278579471, -0.0752249603027732, 1e-10)
  complexNear('IMCSC("4+3i")', -0.0754898329158637, 0.0648774713706355, 1e-10)
  complexNear('IMPRODUCT(IMCSCH("4+3i"),IMSINH("4+3i"))', 1, 0, 1e-12)
  complexNear('IMPRODUCT(IMSECH("4+3i"),IMCOSH("4+3i"))', 1, 0, 1e-12)
  complexNear('IMPRODUCT(IMSEC("1-2i"),IMCOS("1-2i"))', 1, 0, 1e-12)
  complexNear('IMPRODUCT(IMTAN("1-2i"),IMCOT("1-2i"))', 1, 0, 1e-12)
  eq('IMCSC("0")', '#NUM!')
  complexNear('IMEXP(IMLN("2-7i"))', 2, -7, 1e-12)
  complexNear('IMPRODUCT(IMSQRT("-4"),IMSQRT("-4"))', -4, 0, 1e-12)

  // Bessel functions.
  near('BESSELJ(1.9,2)', 0.329925728, 1e-8)
  near('BESSELY(2.5,1)', 0.145918138, 1e-8)
  near('BESSELI(1.5,1)', 0.981666428, 1e-8)
  near('BESSELK(1.5,1)', 0.277387804, 1e-8)
  eq('BESSELJ(0,0)', 1)
  eq('BESSELJ(0,3)', 0)
  near('BESSELJ(1,0)', 0.7651976866, 1e-9)
  near('BESSELJ(1,1)', 0.4400505857, 1e-9)
  near('BESSELJ(-1,1)', -0.4400505857, 1e-9)
  near('BESSELJ(10,0)', -0.2459357645, 1e-9)
  near('BESSELJ(30,1)', -0.1187510626, 1e-9)
  near('BESSELJ(1,10)', 2.630615124e-10, 1e-9)
  near('BESSELY(1,0)', 0.0882569642, 1e-9)
  near('BESSELY(1,1)', -0.7812128213, 1e-9)
  near('BESSELJ(30,0)', -0.0863679835810, 1e-9)
  near('BESSELY(10,0)', 0.0556711673, 1e-9)
  near('BESSELY(30,0)', -0.1172957317, 1e-9)
  near('BESSELK(1,0)', 0.4210244382, 1e-9)
  near('BESSELK(1,1)', 0.6019072302, 1e-9)
  near('BESSELK(2,2)', 0.2537597546, 1e-9)
  near('BESSELI(1,0)', 1.2660658778, 1e-9)
  near('BESSELI(1,1)', 0.565159104, 1e-9)
  near('BESSELI(2,2)', 0.6889484477, 1e-9)
  near('BESSELI(-1,1)', -0.565159104, 1e-9)
  // Wronskians: J1*Y0 - J0*Y1 = 2/(pi x); I1*K0 + I0*K1 = 1/x.
  for (const x of [0.3, 3, 12, 40]) {
    near(`BESSELJ(${x},1)*BESSELY(${x},0)-BESSELJ(${x},0)*BESSELY(${x},1)`, 2 / (Math.PI * x), 1e-10)
  }
  for (const x of [0.5, 5, 20]) {
    near(`(BESSELI(${x},1)*BESSELK(${x},0)+BESSELI(${x},0)*BESSELK(${x},1))*${x}`, 1, 1e-10)
  }
  // Recurrence: J_{n-1} + J_{n+1} = (2n/x) J_n on each evaluation path.
  for (const [x, n] of [[12, 5], [30, 2], [3, 1], [60, 3]]) {
    near(`BESSELJ(${x},${n - 1})+BESSELJ(${x},${n + 1})-${(2 * n) / x}*BESSELJ(${x},${n})`, 0, 1e-10)
  }
  eq('BESSELJ(1,-1)', '#NUM!')
  eq('BESSELY(0,1)', '#NUM!')
  eq('BESSELK(0,1)', '#NUM!')
  eq('BESSELJ("a",1)', '#VALUE!')
  near('BESSELJ(2,1.9)', 0.5767248078, 1e-9) // order truncates to 1
}
